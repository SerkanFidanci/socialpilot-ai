"""PRD §13's planner as values: the obligation, the ten priorities, the mix, the clock.

Everything in this file is a total function over values — no session, no clock, no provider — for
the same reason `content.lifecycle` is: the questions a planner has to answer out loud ("why is
*this* content next?", "why is it published at 20:00 and not at 23:00?") are answered by a table a
test can enumerate rather than by control flow nobody can replay.

Four properties are load-bearing.

**The planner produces demand, not content.** A `content_obligation` is a queue entry: which
business, which content type, in which window, published when, generated by when. Turning one into
a project is a separate, idempotent step that spends credit — and it is separate precisely so that
a planning mistake costs a row somebody can delete rather than a generation somebody paid for.

**The ten priorities are an order, not a weighted score.** §13.2 numbers them, so `rank_key`
returns a tuple with one component per priority in exactly that order and the comparison is
lexicographic. Each component is a *small discrete bucket* rather than a continuous measure, which
is the only way the later priorities can ever be reached: a deadline compared to the minute would
be almost unique, and priorities 3 through 9 would be unreachable code wearing a specification.

**Two of the ten have a field and no rule, and they say so.** §13.2/4 (past performance) needs
data that is first produced in Phase 5, and §13.2/10 (special days) requires by its own wording a
verified calendar source that has not been chosen. Their rules are constants, their inputs are
carried on `RankContext` and read by nothing, and `UNIMPLEMENTED_PRIORITIES` names them so a test
can assert that setting either input changes no order anywhere.

**The mix is measured, never enforced.** §13.3 is a distribution *target*: `measure_mix` reports
how far each category is from its share, and the only thing that reads the deviation is priority 3,
which reorders. There is no function here that refuses an obligation because of a category's share
— a hard quota would punish exactly the business §13.2/1 says to serve first, the one running a
campaign.

The clock lives here too, because "the business's evening" is arithmetic over a timezone and not a
database question. `planned_publish_at` is meaningful in the tenant's own zone and stored in UTC
(AGENTS.md), so every boundary in this file is computed from a local calendar date and converted
once — never by adding 24 hours to an instant, which is a different thing on the two days a year a
zone changes offset.
"""


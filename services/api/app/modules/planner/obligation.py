class ObligationStatus(StrEnum):
    """§13.1's `status`, opened into the states a queue entry actually visits.

    §13.1 shows `planned`. The other five are what happens to a planned thing: it becomes work,
    or it cannot become work and has to say so, or its window closed, or the work it became ended
    one way or the other. `blocked` is the one this slice was asked for by name — an obligation
    that could not be converted must be *visible*, never silently dropped.
    """

    PLANNED = "planned"
    IN_PROGRESS = "in_progress"
    BLOCKED = "blocked"
    FULFILLED = "fulfilled"
    CANCELLED = "cancelled"
    EXPIRED = "expired"


class ObligationEvent(StrEnum):
    """What happened to an obligation, never what to do next (the `lifecycle.py` rule)."""

    CREATED = "created"
    CONVERTED = "converted"
    BLOCKED = "blocked"
    RETRIED = "retried"
    FULFILLED = "fulfilled"
    CANCELLED = "cancelled"
    EXPIRED = "expired"


_TERMINAL_OBLIGATION_STATES: Final[frozenset[ObligationStatus]] = frozenset(
    {ObligationStatus.FULFILLED, ObligationStatus.CANCELLED, ObligationStatus.EXPIRED}
)

_OBLIGATION_TRANSITIONS: Final[
    Mapping[tuple[ObligationStatus, ObligationEvent], ObligationStatus]
] = {
    (ObligationStatus.PLANNED, ObligationEvent.CONVERTED): ObligationStatus.IN_PROGRESS,
    (ObligationStatus.PLANNED, ObligationEvent.BLOCKED): ObligationStatus.BLOCKED,
    # A blocked obligation is not a dead one: the tenant tops up their credit, or the missing
    # product comes back, and the next dispatch pass tries again inside the same window. This
    # edge is why `blocked` is a state rather than a failure code on a cancelled row.
    (ObligationStatus.BLOCKED, ObligationEvent.RETRIED): ObligationStatus.PLANNED,
    (ObligationStatus.BLOCKED, ObligationEvent.CONVERTED): ObligationStatus.IN_PROGRESS,
    (ObligationStatus.IN_PROGRESS, ObligationEvent.FULFILLED): ObligationStatus.FULFILLED,
    # The project ended without reaching a schedule — it failed, or the customer withdrew it.
    # The obligation follows it rather than sitting `in_progress` pointing at a dead project.
    (ObligationStatus.IN_PROGRESS, ObligationEvent.CANCELLED): ObligationStatus.CANCELLED,
    **{
        (status, ObligationEvent.CANCELLED): ObligationStatus.CANCELLED
        for status in (ObligationStatus.PLANNED, ObligationStatus.BLOCKED)
    },
    # Only states that never became work expire. An `in_progress` obligation whose window closed
    # is still producing something the customer will receive, and killing it would throw away a
    # generation that has already been paid for.
    **{
        (status, ObligationEvent.EXPIRED): ObligationStatus.EXPIRED
        for status in (ObligationStatus.PLANNED, ObligationStatus.BLOCKED)
    },
}

INITIAL_OBLIGATION_STATUS: Final = ObligationStatus.PLANNED


def next_obligation_status(
    status: ObligationStatus, event: ObligationEvent
) -> ObligationStatus | None:
    """Where `event` leads from `status`, or `None` when there is no such edge.

    Total over the whole product: the permutation test enumerates every pair and this raises on
    none of them. `None` is a refusal the caller has to handle, never a reason to guess.
    """

    return _OBLIGATION_TRANSITIONS.get((status, event))


def obligation_is_terminal(status: ObligationStatus) -> bool:
    """A status the obligation never leaves: fulfilled, cancelled or expired."""

    return status in _TERMINAL_OBLIGATION_STATES


def obligation_can_cancel(status: ObligationStatus) -> bool:
    """Exactly the non-terminal statuses, derived from the table rather than restated."""

    return next_obligation_status(status, ObligationEvent.CANCELLED) is not None


class ObligationTransitionError(ValueError):
    """A transition the obligation state machine does not draw was attempted."""

    def __init__(self, status: ObligationStatus, event: ObligationEvent) -> None:
        super().__init__(f"{ERROR_OBLIGATION_TRANSITION}: {status.value} -> {event.value}")
        self.code = ERROR_OBLIGATION_TRANSITION
        self.status = status
        self.event = event


def require_obligation_status(status: ObligationStatus, event: ObligationEvent) -> ObligationStatus:
    """`next_obligation_status`, raising rather than returning `None`."""

    target = next_obligation_status(status, event)
    if target is None:
        raise ObligationTransitionError(status, event)
    return target


